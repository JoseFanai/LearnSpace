-- LearnSpace database schema for Supabase (PostgreSQL)
-- Run this in Supabase Dashboard -> SQL Editor after creating a project.
-- Uses Supabase Auth users; never store plaintext passwords in your own tables.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.lesson_progress (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id text not null,
  completed_lessons integer[] not null default '{}',
  last_lesson_index integer not null default 0 check (last_lesson_index >= 0),
  enrolled boolean not null default false,
  updated_at timestamptz not null default now(),
  unique (user_id, course_id)
);

create table if not exists public.assignment_submissions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  assignment_id text not null,
  submission_url text not null,
  status text not null default 'submitted' check (status in ('submitted', 'needs_revision', 'approved')),
  feedback text,
  updated_at timestamptz not null default now(),
  unique (user_id, assignment_id)
);

alter table public.profiles enable row level security;
alter table public.lesson_progress enable row level security;
alter table public.assignment_submissions enable row level security;

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile" on public.profiles
  for select to authenticated using (auth.uid() = id);
drop policy if exists "Users can insert their own profile" on public.profiles;
create policy "Users can insert their own profile" on public.profiles
  for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

